import {
  Entity,
  Column,
  PrimaryGeneratedColumn,
  CreateDateColumn,
  UpdateDateColumn,
  Index,
} from 'typeorm';

export enum SupportDepartment {
  GENERAL_SUPPORT = 'GENERAL_SUPPORT',
  DISPUTE_DESK = 'DISPUTE_DESK',
  BILLING_AND_PAYMENTS = 'BILLING_AND_PAYMENTS',
  FRAUD_AND_SAFETY = 'FRAUD_AND_SAFETY',
}

export enum SupportTicketStatus {
  AI_HANDLING = 'AI_HANDLING',
  ASSIGNED_TO_HUMAN = 'ASSIGNED_TO_HUMAN',
  WAITING_ON_USER = 'WAITING_ON_USER',
  RESOLVED = 'RESOLVED',
  CLOSED = 'CLOSED',
}

export enum SupportPriority {
  LOW = 'LOW',
  MEDIUM = 'MEDIUM',
  HIGH = 'HIGH',
  URGENT = 'URGENT',
}

@Entity()
export class SupportTicket {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Index()
  @Column()
  userId: string;

  @Index()
  @Column({ type: 'varchar', nullable: true })
  jobId: string | null;

  @Index()
  @Column({ type: 'varchar', nullable: true })
  escrowId: string | null;

  @Column({
    type: 'enum',
    enum: SupportDepartment,
    default: SupportDepartment.GENERAL_SUPPORT,
  })
  department: SupportDepartment;

  @Column({
    type: 'enum',
    enum: SupportTicketStatus,
    default: SupportTicketStatus.AI_HANDLING,
  })
  status: SupportTicketStatus;

  @Column({
    type: 'enum',
    enum: SupportPriority,
    default: SupportPriority.MEDIUM,
  })
  priority: SupportPriority;

  @Column({ default: 'General Inquiry' })
  subject: string;

  @Column({ type: 'varchar', nullable: true })
  category: string | null;

  // Succinct, trustworthy case brief generated by Gemini for the human supervisor
  @Column({ type: 'text', nullable: true })
  aiSummary: string | null;

  @Column({ type: 'int', default: 1 })
  aiFrustrationScore: number; // 1 to 10

  @Column({ type: 'varchar', nullable: true })
  assignedAdminId: string | null;

  @Column({ type: 'text', nullable: true })
  resolutionNotes: string | null;

  @Column({ type: 'timestamp', nullable: true })
  resolvedAt: Date | null;

  @CreateDateColumn()
  createdAt: Date;

  @UpdateDateColumn()
  updatedAt: Date;
}
